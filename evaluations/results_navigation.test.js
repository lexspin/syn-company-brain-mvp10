const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../app/results-view.js'),'utf8');
const workspace=fs.readFileSync(path.join(__dirname,'../app/workspace.html'),'utf8');
const result={kind:'memory',id:'result',data:{name:'Actual checked report'}};
const done={kind:'memory',id:'done',updated:'2026-10-13',data:{type:'native-work-request',request_state:'completed',result_ref:'result',name:'Completed request'}};
const failed={kind:'memory',id:'failed',updated:'2026-10-12',data:{type:'native-work-request',request_state:'failed',failure_reason:'Changed sources',name:'Stopped request'}};
const queued={kind:'memory',id:'queued',updated:'2026-10-13',data:{type:'native-work-request',request_state:'queued',name:'Waiting request'}};
const c={state:{runs:[],objects:[failed,queued,done,result],memory_freshness:{}},V:{innerHTML:''},document:{querySelectorAll:()=>[]},runId:null,esc:String,displayName:(o,f)=>o?.data?.name||f,recordLink:(kind,id,label)=>`<a href="#${kind}/${id}">${label}</a>`,resultsSignature:()=>JSON.stringify(c.state),resultState:String,resultLabel:()=>''};
vm.createContext(c);vm.runInContext(source,c);c.runsView();
assert.ok(c.V.innerHTML.indexOf('Saved native results')<c.V.innerHTML.indexOf('Stopped native requests'));
assert.match(c.V.innerHTML,/<details id="nativeResultHistory"><summary>Stopped native requests · 1/);
assert.match(c.V.innerHTML,/Changed sources/);
assert.match(c.V.innerHTML,/Waiting or in progress/);
assert.match(c.V.innerHTML,/#memory\/result/);
assert.match(c.V.innerHTML,/#memory\/failed/);
assert.match(c.V.innerHTML,/<h3>Actual checked report<\/h3>/);
const helper=workspace.slice(workspace.indexOf('function recentOutcomes()'),workspace.indexOf('function overviewView()'));
vm.runInContext(helper,c);
assert.match(c.recentOutcomes(),/Actual checked report/);
assert.doesNotMatch(c.recentOutcomes(),/Stopped request/);
c.state.memory_freshness.result={current:false};
assert.doesNotMatch(c.recentOutcomes(),/Actual checked report/);
console.log('10 results and overview navigation assertions passed');
